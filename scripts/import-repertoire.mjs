// Converts the UI component directory (src/catalog/import/repertoire-ui.sqlite) to JSON so the
// catalogue scripts and Storybook can read it without a SQLite driver.
//
//   node scripts/import-repertoire.mjs [path/to/repertoire-ui.sqlite]
//
// The database holds two tables: `libraries` (stack, platform, licence, maturity, description)
// and `components` (name, category and documentation URL per library). Replace the .sqlite file
// with a newer export and run this again, then `npm run catalog`.
import { writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';

const source = process.argv[2] ?? fileURLToPath(new URL('../src/catalog/import/repertoire-ui.sqlite', import.meta.url));
const out = new URL('../src/catalog/import/repertoire-ui.json', import.meta.url);
const db = new DatabaseSync(source, { readOnly: true });

const metadata = Object.fromEntries(db.prepare('SELECT key, value FROM metadata').all().map((row) => [row.key, row.value]));
const libraries = {};
for (const row of db.prepare('SELECT * FROM libraries ORDER BY id').all()) {
  libraries[row.id] = {
    name: row.name, stack: row.stack, platform: row.platform, license: row.license, maturity: row.maturity,
    description: row.description, url: row.url, catalogUrl: row.catalog_url, sourceStatus: row.source_status, components: [],
  };
}
for (const row of db.prepare('SELECT library_id, name, category, url FROM components ORDER BY library_id, name').all()) {
  libraries[row.library_id].components.push({ name: row.name, category: row.category, url: row.url });
}
db.close();

writeFileSync(out, `${JSON.stringify({ note: 'Generated by scripts/import-repertoire.mjs from repertoire-ui.sqlite. Do not edit by hand.', generatedAt: metadata.generated_at, libraries }, null, 1)}\n`);
const total = Object.values(libraries).reduce((sum, lib) => sum + lib.components.length, 0);
console.log(`${Object.keys(libraries).length} libraries, ${total} components (directory dated ${metadata.generated_at}).`);
